const { contextBridge, ipcRenderer, webUtils } = require("electron");

contextBridge.exposeInMainWorld("host", {
  platform: process.platform,
  ready: () => ipcRenderer.send("ready"),
  showOpenDialog: () => ipcRenderer.send("show-open-dialog"),
  openFiles: (files) => ipcRenderer.send("open-paths", files.map((file) => webUtils.getPathForFile(file))),
  reportFailed: (names) => ipcRenderer.send("open-failed", names),
  chooseExportFolder: (pdfName, title) => ipcRenderer.invoke("choose-export-folder", pdfName, title),
  writeExportFile: (folder, fileName, data) => ipcRenderer.invoke("write-export-file", folder, fileName, data),
  exportFinished: (folder, error) => ipcRenderer.send("export-finished", folder, error),
  saveFile: (path, data) => ipcRenderer.invoke("save-file", path, data),
  saveAs: (defaultName, data, title) => ipcRenderer.invoke("save-as", defaultName, data, title),
  exportDocx: (defaultName, document) => ipcRenderer.invoke("export-docx", defaultName, document),
  pickPDFs: (title) => ipcRenderer.invoke("pick-pdfs", title),
  confirmCloseTab: (name) => ipcRenderer.invoke("confirm-close-tab", name),
  showError: (message, detail) => ipcRenderer.send("show-error", message, detail),
  setDirtyCount: (count) => ipcRenderer.send("set-dirty-count", count),
  popupMenu: (items, x, y) => ipcRenderer.invoke("popup-menu", items, x, y),
  closeWindow: () => ipcRenderer.send("close-window"),
  toggleFullScreen: () => ipcRenderer.send("toggle-fullscreen"),
  setMenuState: (state) => ipcRenderer.send("menu-state", state),
  onMenuAction: (callback) => ipcRenderer.on("menu-action", (_event, action) => callback(action)),
  onOpenFiles: (callback) => ipcRenderer.on("open-files", (_event, files) => callback(files)),
  onFullScreen: (callback) => ipcRenderer.on("fullscreen", (_event, value) => callback(value)),
});
